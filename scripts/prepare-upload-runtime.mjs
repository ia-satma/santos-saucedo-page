import {mkdir,writeFile,readdir,access} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
const root=path.resolve('dist/clamav');
await mkdir(root,{recursive:true});
const config=path.join(root,'freshclam.conf');
await writeFile(config,[`DatabaseDirectory ${root}`,`DatabaseOwner ${os.userInfo().username}`,'DatabaseMirror database.clamav.net','ConnectTimeout 15','ReceiveTimeout 90','MaxAttempts 2','ScriptedUpdates yes','Checks 1',''].join('\n'));
const run=(command,args,timeout=180000)=>new Promise((resolve,reject)=>{const child=spawn(command,args,{stdio:'inherit'});const timer=setTimeout(()=>{child.kill('SIGTERM');reject(new Error(`${command} excedió el tiempo de preparación.`));},timeout);child.once('error',error=>{clearTimeout(timer);reject(error);});child.once('exit',code=>{clearTimeout(timer);code===0?resolve():reject(new Error(`${command} terminó con código ${code}.`));});});
console.log('[uploads] Comprobando FFmpeg y descargando firmas oficiales de ClamAV.');
await run('ffprobe',['-version'],15000);
await run('ffmpeg',['-version'],15000);
await run('freshclam',[`--config-file=${config}`]);
if(!(await readdir(root)).some(name=>/\.(?:cvd|cld)$/.test(name)))throw new Error('No hay firmas oficiales de ClamAV.');
const probe=path.join(root,'readiness.txt');await writeFile(probe,'Santos & Saucedo upload runtime readiness');
await run('clamscan',[`--database=${root}`,'--no-summary',probe],60000);
console.log('[uploads] Video y escáner listos. Firmas incluidas en el artefacto de despliegue.');
